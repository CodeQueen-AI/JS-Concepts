// For loop
for (let i = 1; i <= 5; i++) {
    console.log("For loop:", i);
}

// While loop
let j = 1;
while (j <= 5) {
    console.log("While loop:", j);
    j++;
}

// Do While loop
let k = 1;
do {
    console.log("Do...While loop:", k);
    k++;
} while (k <= 5);

// For...of loop (for arrays)
let fruits = ["Apple", "Banana", "Mango"];
for (let fruit of fruits) {
    console.log("For...of loop:", fruit);
}
